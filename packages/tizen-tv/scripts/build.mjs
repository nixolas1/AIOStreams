#!/usr/bin/env node
// app/ -> build/app (config.js stamped, js/dev stripped, modulepreload injected)
// -> out/AIOStreamsTV.wgt (unsigned zip, deterministic).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { check } from './check-legacy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'app');
const dst = path.join(root, 'build', 'app');
const outFile = path.join(root, 'out', 'AIOStreamsTV.wgt');

function walk(dir, base, out) {
  for (const name of fs.readdirSync(dir).sort()) {
    const p = path.join(dir, name);
    const rel = base ? base + '/' + name : name;
    if (fs.statSync(p).isDirectory()) walk(p, rel, out);
    else out.push(rel);
  }
  return out;
}

// ---- minimal deterministic zip writer ----
const CRC = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
// 2020-01-01 00:00:00 in DOS format
const DOS_TIME = 0;
const DOS_DATE = ((2020 - 1980) << 9) | (1 << 5) | 1;

export function zip(entries) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const e of entries) {
    const name = Buffer.from(e.name, 'utf8');
    const data = e.data;
    const comp = zlib.deflateRawSync(data, { level: 9 });
    const useDeflate = comp.length < data.length;
    const body = useDeflate ? comp : data;
    const crc = crc32(data);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0);
    lh.writeUInt16LE(20, 4);
    lh.writeUInt16LE(0x0800, 6);
    lh.writeUInt16LE(useDeflate ? 8 : 0, 8);
    lh.writeUInt16LE(DOS_TIME, 10);
    lh.writeUInt16LE(DOS_DATE, 12);
    lh.writeUInt32LE(crc, 14);
    lh.writeUInt32LE(body.length, 18);
    lh.writeUInt32LE(data.length, 22);
    lh.writeUInt16LE(name.length, 26);
    lh.writeUInt16LE(0, 28);
    locals.push(lh, name, body);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0);
    ch.writeUInt16LE(20, 4);
    ch.writeUInt16LE(20, 6);
    ch.writeUInt16LE(0x0800, 8);
    ch.writeUInt16LE(useDeflate ? 8 : 0, 10);
    ch.writeUInt16LE(DOS_TIME, 12);
    ch.writeUInt16LE(DOS_DATE, 14);
    ch.writeUInt32LE(crc, 16);
    ch.writeUInt32LE(body.length, 20);
    ch.writeUInt32LE(data.length, 24);
    ch.writeUInt16LE(name.length, 28);
    ch.writeUInt32LE(0x81a40000, 38); // -rw-r--r--
    ch.writeUInt32LE(offset, 42);
    centrals.push(ch, name);
    offset += lh.length + name.length + body.length;
  }
  const cdSize = centrals.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cdSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, ...centrals, end]);
}

function main() {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  fs.rmSync(path.join(root, 'build'), { recursive: true, force: true });
  fs.cpSync(src, dst, { recursive: true });
  fs.rmSync(path.join(dst, 'js', 'dev'), { recursive: true, force: true });

  fs.writeFileSync(path.join(dst, 'js', 'config.js'),
    `// Generated by scripts/build.mjs\nexport const VERSION = ${JSON.stringify(pkg.version)};\nexport const DEV = false;\n`);

  const files = walk(dst, '', []);
  const jsFiles = files.filter((f) => f.startsWith('js/') && f.endsWith('.js'));
  const htmlPath = path.join(dst, 'index.html');
  const links = jsFiles.map((f) => `<link rel="modulepreload" href="${f}">`).join('\n');
  const html = fs.readFileSync(htmlPath, 'utf8');
  if (!html.includes('</head>')) throw new Error('index.html has no </head>');
  fs.writeFileSync(htmlPath, html.replace('</head>', links + '\n</head>'));

  // config.xml first (zip root), then the rest sorted.
  const order = ['config.xml', ...walk(dst, '', []).filter((f) => f !== 'config.xml')];
  const entries = order.map((name) => ({ name, data: fs.readFileSync(path.join(dst, name)) }));
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, zip(entries));
  return { entries: entries.length, bytes: fs.statSync(outFile).size };
}

const r = main();
const c = await check(dst);
if (c.errors.length) {
  for (const e of c.errors) console.error(e);
  process.exit(1);
}
console.log(`built ${path.relative(process.cwd(), outFile)} (${r.entries} files, ${r.bytes} bytes); check-legacy ok`);
